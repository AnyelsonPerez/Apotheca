#!/usr/bin/env bash
# Apotheca — SSL setup with Let's Encrypt (run INSIDE the container)
#
# Usage:  bash /opt/apotheca/infrastructure/proxmox/setup-ssl.sh
#
# Installs certbot, obtains certificates for the given domain, and
# generates the HTTPS server block that nginx-apotheca.conf includes.
set -euo pipefail

INSTALL_DIR="/opt/apotheca"
SSL_CONF="/etc/nginx/sites-available/apotheca-ssl.conf"
CERT_DIR="/etc/letsencrypt/live"

# -- Colors --
RD=$(printf "\033[01;31m")
GN=$(printf "\033[1;92m")
BL=$(printf "\033[36m")
CL=$(printf "\033[m")

msg_info() { echo -e " ${BL}[INFO]${CL} ${1}"; }
msg_ok()   { echo -e " ${GN}[OK]${CL}   ${1}"; }
msg_error(){ echo -e " ${RD}[ERROR]${CL} ${1}"; exit 1; }

# -- Ask for domain --
read -rp "$(echo -e "${BL}Domain (e.g. apotheca.example.com): ${CL}")" DOMAIN
DOMAIN="${DOMAIN:-}"
[[ -z "$DOMAIN" ]] && msg_error "A domain name is required"

# -- Install certbot --
msg_info "Installing certbot"
export DEBIAN_FRONTEND=noninteractive
apt-get install -y -qq certbot python3-certbot-nginx >/dev/null 2>&1
msg_ok "certbot installed"

# -- Obtain certificate --
msg_info "Obtaining certificate for ${DOMAIN}"
certbot certonly --nginx -d "$DOMAIN" --non-interactive --agree-tos --register-unsafely-without-email || \
  certbot certonly --webroot -w /var/www/html -d "$DOMAIN" --non-interactive --agree-tos --register-unsafely-without-email
msg_ok "Certificate obtained"

# -- Generate SSL server block --
msg_info "Generating HTTPS server block"
cat > "$SSL_CONF" <<EOF
# Auto-generated by setup-ssl.sh — do not edit manually.
# HTTPS — Apotheca web + API reverse proxy
server {
    listen 443 ssl;
    http2 on;
    server_name ${DOMAIN};

    ssl_certificate     ${CERT_DIR}/${DOMAIN}/fullchain.pem;
    ssl_certificate_key ${CERT_DIR}/${DOMAIN}/privkey.pem;

    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384;
    ssl_prefer_server_ciphers off;
    ssl_session_cache shared:SSL:10m;
    ssl_session_timeout 1d;

    root /var/www/apotheca;
    index index.html;

    location / {
        try_files \$uri \$uri/ /index.html;
    }

    location /api/ {
        proxy_pass http://127.0.0.1:8000;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }

    location = /api {
        return 301 /api/;
    }

    location /downloads/ {
        alias /var/www/apotheca/downloads/;
        types { application/vnd.android.package-archive apk; }
    }
}
EOF
msg_ok "HTTPS server block generated"

# -- Reload nginx --
msg_info "Reloading nginx"
nginx -t && systemctl reload nginx
msg_ok "nginx reloaded — HTTPS is now active"

echo ""
echo -e " ${GN}SSL configured!${CL}"
echo -e "  ${BL}HTTPS:${CL} https://${DOMAIN}"
echo -e "  ${BL}Renewal:${CL} certbot renew (runs automatically via systemd timer)"
echo ""
